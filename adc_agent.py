"""
adc_agent.py

Competitive Intelligence Agent для ADC (antibody-drug conjugates) в онкологии.

Даёт агенту два инструмента:
- fetch_adc_trials — обёртка над fetch_all_adc_updates() из adc_trials_fetch.py,
  данные из реестра ClinicalTrials.gov;
- web_search — встроенный серверный tool Claude API, для новостей и
  пресс-релизов о сделках/партнёрствах по ADC, которых нет в реестре испытаний.

Системный промпт задаёт агенту роль аналитика конкурентной разведки с явными
guardrails (обязательные источники, разделение фактов реестра и веба, запрет
на домысливание).

Запуск:
    pip install anthropic python-dotenv
    # положи ключ в .env рядом со скриптом: ANTHROPIC_API_KEY=... (файл в .gitignore)
    python adc_agent.py
"""

import json
from anthropic import Anthropic
from dotenv import load_dotenv

from adc_trials_fetch import fetch_all_adc_updates

load_dotenv()  # подхватывает ANTHROPIC_API_KEY из .env

client = Anthropic()  # берёт ключ из переменной окружения ANTHROPIC_API_KEY

MODEL = "claude-opus-5"

# ─────────────────────────────────────────────────────────────
# 1. Системный промпт: роль + формат вывода + guardrails
# ─────────────────────────────────────────────────────────────
SYSTEM_PROMPT = """Ты — аналитик конкурентной разведки в biotech-компании,
специализирующейся на antibody-drug conjugates (ADC) в онкологии.

ТВОЯ ЗАДАЧА:
Проанализировать данные об исследованиях ADC из инструмента fetch_adc_trials,
дополнить их (где это уместно) веб-поиском через web_search и подготовить
сжатую аналитическую сводку для продуктовой команды: что изменилось, у кого,
и почему это может быть важно.

КОГДА КАКОЙ ИНСТРУМЕНТ ИСПОЛЬЗОВАТЬ:
- fetch_adc_trials — основной и единственный источник правды по клиническим
  испытаниям: статус, фаза, спонсор, даты.
- web_search — используй только для того, чего в реестре испытаний нет и
  быть не может: сделки о лицензировании, партнёрства, M&A, регуляторные
  решения (FDA/EMA), финансовые результаты, публичные заявления компаний.
  НЕ используй web_search, чтобы "проверить", дополнить домыслом или
  переинтерпретировать данные fetch_adc_trials — по клиническим испытаниям
  реестр остаётся единственным источником правды.

ФОРМАТ ОТВЕТА:
Для каждого значимого события укажи:
- Компания/спонсор
- Тип события (новое исследование / смена фазы / смена статуса / сделка /
  партнёрство / регуляторное решение / etc.)
- Значимость: Высокая / Средняя / Низкая — с кратким обоснованием (1 предложение)
- Источник — ОБЯЗАТЕЛЬНО для каждого пункта, один из двух форматов:
  [Реестр] NCT ID + прямая ссылка на clinicaltrials.gov
  [Веб] прямая ссылка на статью/пресс-релиз + дата публикации, если доступна
Никогда не смешивай факты реестра и факты веб-поиска в одном пункте без
пометки источника: реестр — это первичные регуляторные данные, веб-поиск —
вторичные источники (новости, пресс-релизы), которые могут быть неточными,
устаревшими или содержать пиар-формулировки.

СТРОГИЕ ПРАВИЛА (не нарушать ни при каких обстоятельствах):
1. Никогда не включай факт в сводку без источника в формате [Реестр] или
   [Веб], как описано выше. Если источника нет — не упоминай факт.
2. Не додумывай мотивы компаний, стратегию или планы, которых нет в данных.
   Если хочешь предположить — явно помечай как "предположение, требует
   проверки", а не подавай как факт.
3. Если данные неполные или противоречивые (например, отсутствует фаза
   исследования, или веб-источник не указывает дату) — явно помечай это
   как "недостаточно данных", а не заполняй пробел собственным домыслом.
4. Ты НЕ принимаешь финальное стратегическое решение за пользователя.
   Твоя задача — дать структурированную сводку с оценкой значимости,
   финальное решение — за человеком.
5. Если инструмент вернул пустой результат или ошибку — сообщи об этом
   прямо, не выдумывай данные. Это касается и web_search: если поиск не
   дал релевантных результатов, так и напиши.
6. Никогда не выдавай новость или слух из web_search за подтверждённый факт
   из клинического реестра, и наоборот — источник [Реестр]/[Веб] обязателен
   и должен быть проверяемым (реальная ссылка, а не выдуманная).
"""

# ─────────────────────────────────────────────────────────────
# 2. Схема инструмента (tool) для function calling
# ─────────────────────────────────────────────────────────────
TOOLS = [
    {
        "name": "fetch_adc_trials",
        "description": (
            "Ищет исследования ADC (antibody-drug conjugates) в онкологии "
            "в реестре ClinicalTrials.gov, обновлённые за последние N дней. "
            "Возвращает список исследований с полями: nct_id, title, status, "
            "phase, sponsor, conditions, interventions, last_update, url. "
            "НЕ содержит сделок, партнёрств или новостей — только "
            "зарегистрированные клинические испытания."
        ),
        "input_schema": {
            "type": "object",
            "properties": {
                "days_back": {
                    "type": "integer",
                    "description": "За сколько последних дней искать обновления (по умолчанию 90)",
                }
            },
            "required": [],
        },
    },
    # Встроенный серверный tool Claude API — выполняется на стороне Anthropic,
    # execute_tool() его не обрабатывает. Ограничиваем max_uses, чтобы агент
    # не уходил в бесконтрольный веб-серфинг за один прогон.
    {
        "type": "web_search_20250305",
        "name": "web_search",
        "max_uses": 5,
    },
]


def execute_tool(tool_name: str, tool_input: dict) -> str:
    """Выполняет вызов инструмента и возвращает результат как строку JSON."""
    if tool_name == "fetch_adc_trials":
        days_back = tool_input.get("days_back", 90)
        try:
            results = fetch_all_adc_updates(days_back=days_back)
            return json.dumps(results, ensure_ascii=False)
        except Exception as e:
            # Явно возвращаем ошибку агенту, а не падаем молча —
            # агент должен честно сообщить пользователю о проблеме.
            return json.dumps({"error": str(e)}, ensure_ascii=False)
    return json.dumps({"error": f"Неизвестный инструмент: {tool_name}"})


def run_agent(user_query: str, max_turns: int = 5) -> str:
    """
    Основной цикл агента: отправляет запрос, обрабатывает tool_use,
    выполняет инструмент, возвращает результат модели, повторяет
    до финального текстового ответа.
    """
    messages = [{"role": "user", "content": user_query}]

    for turn in range(max_turns):
        # Стриминг + большой max_tokens: при ~300 исследованиях в выдаче
        # инструмента развёрнутая сводка легко упирается в лимит, а без
        # стриминга такой большой max_tokens рискует таймаутом запроса.
        with client.messages.stream(
            model=MODEL,
            max_tokens=32000,
            system=SYSTEM_PROMPT,
            tools=TOOLS,
            messages=messages,
        ) as stream:
            response = stream.get_final_message()

        # web_search — серверный tool: Anthropic выполняет поиск сама и
        # кладёт результат в тот же ответ как server_tool_use +
        # web_search_tool_result. Здесь только логируем факт вызова —
        # execute_tool() его не касается, а result уже внутри response.content.
        for block in response.content:
            if block.type == "server_tool_use":
                print(f"  [Агент ищет в вебе: {block.name}({block.input})]")

        # Если модель закончила без вызова инструмента — возвращаем финальный текст
        if response.stop_reason != "tool_use":
            text = "".join(
                block.text for block in response.content if block.type == "text"
            )
            if response.stop_reason == "max_tokens":
                text += "\n\n[ВНИМАНИЕ: ответ обрезан по лимиту max_tokens, сводка неполная]"
            return text

        # Модель запросила вызов инструмента(ов)
        messages.append({"role": "assistant", "content": response.content})

        tool_results = []
        for block in response.content:
            if block.type == "tool_use":
                print(f"  [Агент вызывает инструмент: {block.name}({block.input})]")
                result = execute_tool(block.name, block.input)
                tool_results.append(
                    {
                        "type": "tool_result",
                        "tool_use_id": block.id,
                        "content": result,
                    }
                )

        messages.append({"role": "user", "content": tool_results})

    return "Достигнут лимит итераций агента без финального ответа."


if __name__ == "__main__":
    query = "Подготовь сводку по значимым обновлениям в ADC-исследованиях за последние 90 дней."
    print(f"Запрос: {query}\n")
    answer = run_agent(query)
    print("\n--- Сводка агента ---\n")
    print(answer)
